from pathlib import Path
from datetime import datetime

from openpyxl import Workbook


def _safe_project_name(project_name: str) -> str:
    sanitized = ''.join(ch for ch in project_name.strip() if ch not in r'\/:*?"<>|')
    return sanitized or 'unknown'


def run(input_path: str, output_dir: str, params: dict) -> dict:
    """Generate a basic monthly finance workbook.

    Real financial logic can replace this placeholder while keeping I/O contract.
    """
    output_root = Path(output_dir)
    output_root.mkdir(parents=True, exist_ok=True)

    project_name = _safe_project_name(params.get('project_name', 'unknown'))
    report_month = params.get('report_month', datetime.utcnow().strftime('%Y-%m'))
    resolved_paths = params.get('resolved_file_paths', {})

    filename = f'月度财务报表_{project_name}_美国站_{report_month}.xlsx'
    result_path = output_root / filename

    workbook = Workbook()
    summary_ws = workbook.active
    summary_ws.title = '总览草稿'
    summary_ws.append(['字段', '值'])
    summary_ws.append(['项目名称', project_name])
    summary_ws.append(['账期', report_month])
    summary_ws.append(['交易CSV', resolved_paths.get('transaction_report', input_path)])
    summary_ws.append(['月度总结PDF', resolved_paths.get('monthly_summary_pdf', '')])

    accounting_ws = workbook.create_sheet(title='报表核算')
    accounting_ws.append(['分类', '金额', '说明'])
    accounting_ws.append(['收入合计', '', '等待后端财务逻辑填充'])
    accounting_ws.append(['支出合计', '', '等待后端财务逻辑填充'])
    accounting_ws.append(['推广占比', '', '等待后端财务逻辑填充'])

    workbook.save(result_path)

    return {
        'result_path': str(result_path.resolve()),
        'filename': filename,
        'message': 'Monthly report generated by placeholder script',
    }
